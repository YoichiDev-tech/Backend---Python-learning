# objects & methods
course = 'Python for Beginners'
print(course.upper()) # converts string to uppercase
print(course.find('y')) # finds the index of the first occurrence of 'y' in the string
print(course.find('for')) # returns the index of the first occurrence of 'for' in the string
print(course.replace('for', '4')) # replaces 'for' with '4' in the string
print('Python' in course) # checks if 'Python' is in the string, returns True or False